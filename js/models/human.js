const SIDE = { r: ['ขวา', 'Right'], l: ['ซ้าย', 'Left'] };

const model = {
  id: 'human',
  title: 'ร่างกายมนุษย์',
  floorY: BODY_Y - 0.02,
  camera: {
    dir: [-0.3, 0.12, 1],
    radius: [3.4, 4.5, 6.4, 6.6, 7.2, 7.2, 7.6],
    target: [0, 0, 0],
    targetEnd: [-0.55, 0, 0.15], // เลื่อนภาพไปทางขวาให้ชั้นเส้นประสาทไม่ถูกการ์ดบัง
  },
  credit:
    'โมเดล 3D: <a href="https://www.z-anatomy.com" target="_blank" rel="noopener">Z-Anatomy</a> ' +
    '(<a href="https://creativecommons.org/licenses/by-sa/4.0/" target="_blank" rel="noopener">CC BY-SA 4.0</a>) ' +
    'พัฒนาจาก BodyParts3D © DBCLS — ปรับขนาดไฟล์สำหรับเว็บ',
  stages,
  parts: [],

  async prepare(onProgress) {
    const loader = new GLTFLoader().setMeshoptDecoder(MeshoptDecoder);
    const names = Object.keys(LAYERS);
    const progress = names.map(() => 0);
    const gltfs = await Promise.all(
      names.map((layer, i) =>
        loader.loadAsync(new URL(`${layer}.glb`, BASE).href, (e) => {
          if (e.total) progress[i] = e.loaded / e.total;
          onProgress(progress.reduce((a, b) => a + b, 0) / names.length);
        }),
      ),
    );

    const parts = [];
    names.forEach((layer, li) => {
      const cfg = LAYERS[layer];
      const root = gltfs[li].scene;
      root.updateMatrixWorld(true);

      const items = [];
      root.traverse((o) => {
        if (!o.isMesh) return;
        // แปลงพิกัดที่ถูกบีบอัดเป็น float แล้ววางในพิกัดโลก
        const src = o.geometry.attributes.position;
        const pos = new Float32Array(src.count * 3);
        for (let k = 0; k < src.count; k++) {
          pos[k * 3] = src.getX(k);
          pos[k * 3 + 1] = src.getY(k);
          pos[k * 3 + 2] = src.getZ(k);
        }
        const g = new THREE.BufferGeometry();
        g.setAttribute('position', new THREE.BufferAttribute(pos, 3));
        g.setIndex(o.geometry.index);
        g.applyMatrix4(o.matrixWorld);
        g.translate(0, BODY_Y, 0);
        g.computeVertexNormals();
        g.computeBoundingBox();
        items.push({ id: o.name, g, center: g.boundingBox.getCenter(new THREE.Vector3()) });
      });

      const pivot = new THREE.Vector3();
      if (cfg.pivot) pivot.set(...cfg.pivot);
      else {
        items.forEach((it) => pivot.add(it.center));
        pivot.divideScalar(items.length || 1);
      }

      for (const it of items) {
        const m = /^(.*)_([rl])$/.exec(it.id);
        const base = m ? m[1] : it.id;
        const side = m ? m[2] : null;
        const info = INFO[base];
        if (!info) continue;
        const offset = it.center.clone().sub(pivot).multiplyScalar(cfg.spread).add(new THREE.Vector3(...cfg.shift));
        const material = new THREE.MeshStandardMaterial({
          color: COLORS[base] ?? cfg.color,
          roughness: cfg.rough,
          metalness: 0.05,
          side: THREE.DoubleSide,
        });
        const mesh = new THREE.Mesh(it.g, material);
        parts.push({
          id: it.id,
          stage: cfg.stage,
          offset: offset.toArray(),
          name: side ? `${info.name} (${SIDE[side][0]})` : info.name,
          short: info.name,
          en: side ? `${info.en} (${SIDE[side][1]})` : info.en,
          desc: info.desc,
          facts: info.facts,
          noLabel: side === 'l', // คู่ซ้าย-ขวาแสดงป้ายเฉพาะข้างขวา
          build: () => {
            const group = new THREE.Group();
            group.add(mesh);
            return group;
          },
        });
      }
    });
    parts.sort((a, b) => a.stage - b.stage);
    this.parts = parts;
  },
};

export default model;
