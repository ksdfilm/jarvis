function plutoTexture() {
  const c = document.createElement('canvas');
  c.width = 1024;
  c.height = 512;
  const g = c.getContext('2d');
  g.fillStyle = '#b89a78';
  g.fillRect(0, 0, 1024, 512);
  for (let i = 0; i < 260; i++) {
    g.fillStyle = `rgba(${90 + Math.random() * 60},${60 + Math.random() * 40},${40 + Math.random() * 30},0.25)`;
    g.beginPath();
    g.arc(Math.random() * 1024, Math.random() * 512, 6 + Math.random() * 40, 0, Math.PI * 2);
    g.fill();
  }
  g.fillStyle = '#efe6da';
  g.beginPath();
  const [hx, hy, s] = [560, 270, 70];
  g.moveTo(hx, hy + s);
  g.bezierCurveTo(hx - 2.2 * s, hy - 0.2 * s, hx - 0.8 * s, hy - 1.6 * s, hx, hy - 0.6 * s);
  g.bezierCurveTo(hx + 0.8 * s, hy - 1.6 * s, hx + 2.2 * s, hy - 0.2 * s, hx, hy + s);
  g.fill();
  const t = new THREE.CanvasTexture(c);
  t.colorSpace = THREE.SRGBColorSpace;
  return t;
}

// ครึ่งทรงกลม: side -1 = ซีกซ้าย (x<0, หน้าตัดหัน +x), +1 = ซีกขวา
function half(layer, rIn, side, tex) {
  const g = new THREE.Group();
  const phiStart = side < 0 ? -Math.PI / 2 : Math.PI / 2;
  const geo = new THREE.SphereGeometry(layer.r, 96, 64, phiStart, Math.PI);
  // ให้พิกัดภาพตรงกับทรงกลมเต็มดวง (ค่าเริ่มต้นจะยืดภาพทั้งภาพลงบนครึ่งเดียว)
  const uv = geo.attributes.uv;
  for (let i = 0; i < uv.count; i++) uv.setX(i, (phiStart + uv.getX(i) * Math.PI) / (Math.PI * 2));
  const translucent = layer.opacity !== undefined;
  const shellMat = new THREE.MeshStandardMaterial({
    color: tex ? 0xffffff : layer.color,
    map: tex ?? null,
    roughness: 0.85,
    metalness: 0,
    transparent: translucent,
    opacity: layer.opacity ?? 1,
    depthWrite: !translucent,
    side: THREE.DoubleSide,
  });
  if (layer.glow) {
    shellMat.emissive.setHex(tex ? 0xffffff : layer.color);
    if (tex) shellMat.emissiveMap = tex;
    shellMat.emissiveIntensity = layer.glow;
    shellMat.userData.glow = true;
  }
  g.add(new THREE.Mesh(geo, shellMat));
  // หน้าตัด: วงแหวนความหนาของชั้นนี้ (ชั้นในสุดเป็นวงกลมเต็ม)
  const faceGeo = rIn > 0 ? new THREE.RingGeometry(rIn, layer.r, 96, 1) : new THREE.CircleGeometry(layer.r, 96);
  const cutColor = layer.cut ?? layer.color;
  const faceMat = new THREE.MeshStandardMaterial({
    color: cutColor,
    roughness: 0.9,
    transparent: translucent,
    opacity: translucent ? layer.opacity * 0.45 : 1, // จางพอไม่ให้เห็นเป็นแถบทะลุซีกขวาตอนยังประกอบอยู่
    depthWrite: !translucent,
    side: THREE.DoubleSide,
  });
  if (layer.glow) {
    faceMat.emissive.setHex(cutColor);
    faceMat.emissiveIntensity = layer.glow * 0.8;
    faceMat.userData.glow = true;
  }
  const face = new THREE.Mesh(faceGeo, faceMat);
  face.rotation.y = side < 0 ? Math.PI / 2 : -Math.PI / 2;
  g.add(face);
  return g;
}

// วงแหวนดาวเสาร์ (ภาพไล่จากขอบในไปขอบนอก)
function saturnRings(tex) {
  const ri = 1.24;
  const ro = 2.27;
  const geo = new THREE.RingGeometry(ri, ro, 160, 1);
  const pos = geo.attributes.position;
  const uv = geo.attributes.uv;
  for (let i = 0; i < pos.count; i++) uv.setXY(i, (Math.hypot(pos.getX(i), pos.getY(i)) - ri) / (ro - ri), 0.5);
  const mat = new THREE.MeshStandardMaterial({ map: tex, transparent: true, alphaTest: 0.02, side: THREE.DoubleSide, roughness: 0.9, depthWrite: false });
  const m = new THREE.Mesh(geo, mat);
  m.rotation.x = -Math.PI / 2 + 0.12;
  return m;
}

